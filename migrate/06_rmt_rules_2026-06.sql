-- นโยบายใหม่ (สรุป): แทบทุกสายวิ่งเดี่ยว ยกเว้น 2 เคส
--   1) ลาดบัวขาว (CHP12): ≤13 คน = รถตู้ / ≥14 คน = รถบัส (CHP12-2 cap 42) — ไม่รวมสายอื่น
--   2) หนามแดง (CHP07) + ประเวศ (CHP08): รวมเป็น "หนามแดง" คันเดียวเสมอ
--   3) สายอื่นที่เคยมีเงื่อนไขรวม: วิ่งเดี่ยว (never_merge)
--
-- กลไก engine ([chp2/pack.js] planSlot ลำดับ P1 never_merge -> P2-6 dispatch_rule
-- -> P5 bus_threshold -> P7 min_solo_pax -> merge): ใช้ flag ในตาราง chp2.* ล้วน
-- ไม่แตะโค้ด engine
-- ============================================================================

-- #1 ลาดบัวขาว: ลด bus_threshold 26 -> 14 (≥14 = บัส), min_solo_pax = 1 (ต่ำกว่า 14
--    = ตู้เดี่ยวเสมอ ไม่ตกไป merge), bus_route_id = 25 (CHP12-2) คงเดิม.
--    ปิด dispatch_rule ขาออก (id 2: จุด1-7 จัดเอง ไม่งั้น 12+13) เพราะ P2-6 มาก่อน P5
--    ถ้าไม่ปิด ขาออกจะไม่มีวันเป็นบัส และอาจยุบเข้า 12+13
UPDATE chp2.route          SET bus_threshold = 14, min_solo_pax = 1 WHERE id = 22;  -- CHP12
UPDATE chp2.dispatch_rule  SET is_active = false                    WHERE id = 2;

-- #2 หนามแดง + ประเวศ: เอา min_solo_pax ออก (เดิม 7 -> ทำให้แต่ละสายแยกคันเมื่อ ≥7)
--    ให้ตกเข้ากลุ่มรวม D เสมอ; ชี้ผลรวมของกลุ่ม D ไปที่สาย CHP07 เพื่อให้คันรวมชื่อ
--    "หนามแดง" (เดิมชี้ route 17 'รวม หนามแดง + ประเวศ'). ยอดรวมไม่เคยเกิน 13 -> ลงตู้เดียว
UPDATE chp2.route        SET min_solo_pax = NULL WHERE id IN (7, 8);  -- CHP07, CHP08
UPDATE chp2.merge_group  SET result_route_id = 7 WHERE id = 3;        -- group D -> หนามแดง

-- #3 สายอื่นที่เคยมีเงื่อนไขรวม -> วิ่งเดี่ยวเสมอ (never_merge ตัด P2-6/merge ทั้งหมด)
--    วัดสว่าง แคราย คลอง14 คลอง16 หมู่บ้านริมบึง คลองเจ้า แปดริ้ว วัดเกาะ กรุงเทพ
--    สนามชัย ดงน้อย แปลงยาว  (บางน้ำเปรี้ยว CHP16 never_merge=true อยู่แล้ว;
--    CHP07/08/12 ยกเว้นตามข้อ 1-2). dispatch_rule ของสายเหล่านี้ถูก never_merge
--    override (P1 มาก่อน) จึง inert — คงไว้เฉย ๆ ได้
UPDATE chp2.route SET never_merge = true WHERE id IN (1,2,3,4,5,6,9,10,11,20,21,23);
